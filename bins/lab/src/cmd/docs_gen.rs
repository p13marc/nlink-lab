//! `nlink-lab docs-gen`.

use std::path::{Path, PathBuf};

use crate::ctx::Ctx;

#[derive(clap::Args)]
pub struct Args {
    /// Output directory.
    #[arg(long, default_value = "docs/cli")]
    pub out: PathBuf,

    /// Also write the JSON Schemas of every typed `--json` payload
    /// (generated with `schemars`) into this directory.
    #[arg(long, value_name = "DIR")]
    pub schemas: Option<PathBuf>,

    /// Delete the generated pages of commands that no longer exist (pages
    /// without the generated block are kept).
    #[arg(long)]
    pub prune: bool,

    /// Print every visible command path (`snapshot save`), one per line,
    /// and write nothing.
    #[arg(long)]
    pub list_commands: bool,
}

/// The marker lines around the generated block of a page. Hand-written
/// prose above and below them is kept; only the block is regenerated
/// (CI diffs the result).
const START: &str = "<!-- cli-ref:start (generated by `nlink-lab docs-gen`; do not edit) -->";
const END: &str = "<!-- cli-ref:end -->";

/// Every visible command below `cmd`, depth first: its path words and
/// the command.
fn commands(cmd: &clap::Command, path: &[String], out: &mut Vec<(Vec<String>, clap::Command)>) {
    for sub in cmd.get_subcommands() {
        if sub.is_hide_set() || sub.get_name() == "help" {
            continue;
        }
        let mut p = path.to_vec();
        p.push(sub.get_name().to_string());
        out.push((p.clone(), sub.clone()));
        commands(sub, &p, out);
    }
}

/// The page of `path`: `snapshot save` → `snapshot-save.md`.
fn page_name(path: &[String]) -> String {
    format!("{}.md", path.join("-"))
}

fn write_page(dir: &Path, path: &[String], sub: &clap::Command) -> nlink_lab::Result<()> {
    let title = format!("nlink-lab {}", path.join(" "));
    let mut sub = sub.clone().name(clap::builder::Str::from(
        title.clone().leak() as &'static str
    ));
    let help = sub.render_long_help().to_string();
    let block = format!("{START}\n\n```text\n{}\n```\n\n{END}\n", help.trim_end());
    let file = dir.join(page_name(path));
    let page = match std::fs::read_to_string(&file) {
        Ok(existing) if existing.contains(START) && existing.contains(END) => {
            let a = existing.find(START).unwrap_or(0);
            let b = existing
                .find(END)
                .map(|i| i + END.len())
                .unwrap_or(existing.len());
            let tail = existing[b..].trim_start_matches('\n');
            format!(
                "{}{}{}",
                &existing[..a],
                block,
                if tail.is_empty() {
                    String::new()
                } else {
                    format!("\n{tail}")
                }
            )
        }
        Ok(existing) => format!("{}\n\n## Reference\n\n{block}", existing.trim_end()),
        Err(_) => format!("# `{title}`\n\n## Reference\n\n{block}"),
    };
    std::fs::write(&file, page)?;
    Ok(())
}

pub fn run(_ctx: &Ctx, args: Args) -> nlink_lab::Result<()> {
    let Args {
        out,
        schemas,
        prune,
        list_commands,
    } = args;
    let mut all = Vec::new();
    commands(&crate::command(), &[], &mut all);
    if list_commands {
        for (path, _) in &all {
            println!("{}", path.join(" "));
        }
        return Ok(());
    }
    if let Some(dir) = schemas {
        std::fs::create_dir_all(&dir)?;
        let mut n = 0;
        for (stem, schema) in crate::output::all_schemas() {
            let text = serde_json::to_string_pretty(&schema)?;
            std::fs::write(dir.join(format!("{stem}.schema.json")), format!("{text}\n"))?;
            n += 1;
        }
        eprintln!("wrote {n} schemas to {}", dir.display());
    }
    std::fs::create_dir_all(&out)?;
    for (path, sub) in &all {
        write_page(&out, path, sub)?;
    }
    eprintln!("wrote {} pages to {}", all.len(), out.display());
    if prune {
        let pages: Vec<String> = all.iter().map(|(p, _)| page_name(p)).collect();
        for entry in std::fs::read_dir(&out)? {
            let file = entry?.path();
            let name = file
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or_default();
            if !name.ends_with(".md") || pages.iter().any(|p| p == name) {
                continue;
            }
            // only what docs-gen wrote: an index or a guide stays
            if std::fs::read_to_string(&file).is_ok_and(|t| t.contains(START)) {
                std::fs::remove_file(&file)?;
                eprintln!("removed {}", file.display());
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nested_commands_get_their_own_pages() {
        let cmd = clap::Command::new("t").subcommand(
            clap::Command::new("snapshot")
                .subcommand(clap::Command::new("save"))
                .subcommand(clap::Command::new("ls").hide(true)),
        );
        let mut all = Vec::new();
        commands(&cmd, &[], &mut all);
        let names: Vec<String> = all.iter().map(|(p, _)| page_name(p)).collect();
        assert_eq!(names, ["snapshot.md", "snapshot-save.md"]);
    }

    #[test]
    fn prune_keeps_pages_it_did_not_write() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("README.md"), "# index\n").unwrap();
        std::fs::write(
            dir.path().join("gone.md"),
            format!("# gone\n\n{START}\n\n{END}\n"),
        )
        .unwrap();
        run(
            &Ctx {
                format: crate::output::Format::Text,
                json: false,
                quiet: true,
                verbose: false,
            },
            Args {
                out: dir.path().to_path_buf(),
                schemas: None,
                prune: true,
                list_commands: false,
            },
        )
        .unwrap();
        assert!(dir.path().join("README.md").exists());
        assert!(!dir.path().join("gone.md").exists());
        assert!(dir.path().join("deploy.md").exists());
    }
}
