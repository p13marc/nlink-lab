//! `nlink-lab docs-gen`.

use std::path::{Path, PathBuf};

use crate::ctx::Ctx;

#[derive(clap::Args)]
pub struct Args {
    /// Output directory.
    #[arg(long, default_value = "docs/cli")]
    pub out: PathBuf,

    /// Also write the JSON Schemas of every typed `--json` payload
    /// (generated with `schemars`) into this directory.
    #[arg(long, value_name = "DIR")]
    pub schemas: Option<PathBuf>,

    /// Delete the generated pages of commands that no longer exist (pages
    /// without the generated block are kept).
    #[arg(long)]
    pub prune: bool,

    /// Print every visible command path (`snapshot save`), one per line,
    /// and write nothing.
    #[arg(long)]
    pub list_commands: bool,

    /// The repository whose README.md, CLAUDE.md and docs/ get their
    /// `<!-- count:NAME -->N<!-- /count -->` markers filled in.
    #[arg(long, default_value = ".")]
    pub root: PathBuf,
}

/// The marker lines around the generated block of a page. Hand-written
/// prose above and below them is kept; only the block is regenerated
/// (CI diffs the result).
const START: &str = "<!-- cli-ref:start (generated by `nlink-lab docs-gen`; do not edit) -->";
const END: &str = "<!-- cli-ref:end -->";

/// The marker lines around the command index of the reference's
/// `README.md`: the commands under their `cli::GROUPS` headings.
const INDEX_START: &str =
    "<!-- cli-index:start (generated by `nlink-lab docs-gen` from cli::GROUPS; do not edit) -->";
const INDEX_END: &str = "<!-- cli-index:end -->";

/// A generated number in prose: `<!-- count:NAME -->N<!-- /count -->`.
/// Every count the docs state is one of these, so it cannot go stale: CI
/// regenerates them and fails on a diff (#345).
const COUNT_OPEN: &str = "<!-- count:";
const COUNT_CLOSE: &str = "<!-- /count -->";

/// The docs with generated counts: README.md, CLAUDE.md and docs/, minus
/// the historical plans (the docs gate reads the same files).
pub(crate) fn doc_files(root: &Path) -> Vec<PathBuf> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                if p.file_name().is_some_and(|n| n == "plans") {
                    continue;
                }
                walk(&p, out);
            } else if p.extension().is_some_and(|x| x == "md") {
                out.push(p);
            }
        }
    }
    let mut out = vec![root.join("README.md"), root.join("CLAUDE.md")];
    walk(&root.join("docs"), &mut out);
    out.sort();
    out
}

/// The `.nll` files under `dir`: directly in it, or anywhere below.
fn count_nll(dir: &Path, recursive: bool) -> usize {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return 0;
    };
    entries
        .flatten()
        .map(|e| e.path())
        .map(|p| {
            if p.is_dir() {
                if recursive { count_nll(&p, true) } else { 0 }
            } else {
                usize::from(p.extension().is_some_and(|x| x == "nll"))
            }
        })
        .sum()
}

/// What each count marker says, by name.
pub(crate) fn counts(root: &Path) -> std::collections::BTreeMap<&'static str, String> {
    let commands: usize = crate::cli::GROUPS.iter().map(|(_, c)| c.len()).sum();
    let rules = nlink_lab::rule_ids();
    let warnings = rules
        .iter()
        .filter(|id| nlink_lab::rule_severity(id) == Some(nlink_lab::Severity::Warning))
        .count();
    let examples = root.join("examples");
    [
        ("cli-commands", commands.to_string()),
        ("validator-rules", rules.len().to_string()),
        ("validator-errors", (rules.len() - warnings).to_string()),
        ("validator-warnings", warnings.to_string()),
        ("lint-rules", nlink_lab::LINT_RULE_IDS.len().to_string()),
        ("examples", count_nll(&examples, false).to_string()),
        ("examples-all", count_nll(&examples, true).to_string()),
        ("api-version", nlink_lab::api::api_version_string()),
    ]
    .into_iter()
    .collect()
}

/// `text` with every count marker's number set to what it counts; an
/// unknown name or an unclosed marker is an error.
fn fill_counts(
    text: &str,
    counts: &std::collections::BTreeMap<&'static str, String>,
) -> Result<String, String> {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(at) = rest.find(COUNT_OPEN) {
        let after = &rest[at + COUNT_OPEN.len()..];
        let name_end = after
            .find("-->")
            .ok_or_else(|| "a count marker without `-->`".to_string())?;
        let name = after[..name_end].trim();
        let value = counts
            .get(name)
            .ok_or_else(|| format!("unknown count `{name}`"))?;
        let body = &after[name_end + 3..];
        let close = body
            .find(COUNT_CLOSE)
            .ok_or_else(|| format!("count `{name}` is not closed by `{COUNT_CLOSE}`"))?;
        out.push_str(&rest[..at]);
        out.push_str(&format!("{COUNT_OPEN}{name} -->{value}{COUNT_CLOSE}"));
        rest = &body[close + COUNT_CLOSE.len()..];
    }
    out.push_str(rest);
    Ok(out)
}

/// The command index: a table per `cli::GROUPS` heading.
fn index(cmd: &clap::Command) -> String {
    let mut out = String::new();
    for (group, names) in crate::cli::GROUPS {
        out.push_str(&format!(
            "\n## {group}\n\n| Command | What |\n|---------|------|\n"
        ));
        for name in *names {
            let about = crate::cli::summary(cmd, name).replace('|', "\\|");
            out.push_str(&format!("| [`{name}`]({name}.md) | {about} |\n"));
        }
    }
    out
}

/// Rewrite the command index between its markers in `<dir>/README.md`.
fn write_index(dir: &Path, cmd: &clap::Command) -> nlink_lab::Result<()> {
    let file = dir.join("README.md");
    let Ok(text) = std::fs::read_to_string(&file) else {
        return Ok(());
    };
    let (Some(a), Some(b)) = (text.find(INDEX_START), text.find(INDEX_END)) else {
        return Ok(());
    };
    let page = format!(
        "{}{INDEX_START}\n{}\n{}",
        &text[..a],
        index(cmd),
        &text[b..]
    );
    std::fs::write(&file, page)?;
    Ok(())
}

/// Every visible command below `cmd`, depth first: its path words and
/// the command.
fn commands(cmd: &clap::Command, path: &[String], out: &mut Vec<(Vec<String>, clap::Command)>) {
    for sub in cmd.get_subcommands() {
        if sub.is_hide_set() || sub.get_name() == "help" {
            continue;
        }
        let mut p = path.to_vec();
        p.push(sub.get_name().to_string());
        out.push((p.clone(), sub.clone()));
        commands(sub, &p, out);
    }
}

/// The page of `path`: `snapshot save` → `snapshot-save.md`.
fn page_name(path: &[String]) -> String {
    format!("{}.md", path.join("-"))
}

fn write_page(dir: &Path, path: &[String], sub: &clap::Command) -> nlink_lab::Result<()> {
    let title = format!("nlink-lab {}", path.join(" "));
    let mut sub = sub.clone().name(clap::builder::Str::from(
        title.clone().leak() as &'static str
    ));
    let help = sub.render_long_help().to_string();
    let block = format!("{START}\n\n```text\n{}\n```\n\n{END}\n", help.trim_end());
    let file = dir.join(page_name(path));
    let page = match std::fs::read_to_string(&file) {
        Ok(existing) if existing.contains(START) && existing.contains(END) => {
            let a = existing.find(START).unwrap_or(0);
            let b = existing
                .find(END)
                .map(|i| i + END.len())
                .unwrap_or(existing.len());
            let tail = existing[b..].trim_start_matches('\n');
            format!(
                "{}{}{}",
                &existing[..a],
                block,
                if tail.is_empty() {
                    String::new()
                } else {
                    format!("\n{tail}")
                }
            )
        }
        Ok(existing) => format!("{}\n\n## Reference\n\n{block}", existing.trim_end()),
        Err(_) => format!("# `{title}`\n\n## Reference\n\n{block}"),
    };
    std::fs::write(&file, page)?;
    Ok(())
}

pub fn run(_ctx: &Ctx, args: Args) -> nlink_lab::Result<()> {
    let Args {
        out,
        schemas,
        prune,
        list_commands,
        root,
    } = args;
    let mut all = Vec::new();
    commands(&crate::command(), &[], &mut all);
    if list_commands {
        for (path, _) in &all {
            println!("{}", path.join(" "));
        }
        return Ok(());
    }
    if let Some(dir) = schemas {
        std::fs::create_dir_all(&dir)?;
        let mut n = 0;
        for (stem, schema) in crate::output::all_schemas() {
            let text = serde_json::to_string_pretty(&schema)?;
            std::fs::write(dir.join(format!("{stem}.schema.json")), format!("{text}\n"))?;
            n += 1;
        }
        eprintln!("wrote {n} schemas to {}", dir.display());
    }
    std::fs::create_dir_all(&out)?;
    for (path, sub) in &all {
        write_page(&out, path, sub)?;
    }
    eprintln!("wrote {} pages to {}", all.len(), out.display());
    write_index(&out, &crate::command())?;
    let counts = counts(&root);
    let mut filled = 0;
    for file in doc_files(&root) {
        let Ok(text) = std::fs::read_to_string(&file) else {
            continue;
        };
        let new = fill_counts(&text, &counts)
            .map_err(|e| nlink_lab::Error::invalid_argument(format!("{}: {e}", file.display())))?;
        if new != text {
            std::fs::write(&file, new)?;
            filled += 1;
        }
    }
    if filled > 0 {
        eprintln!("updated the counts in {filled} file(s)");
    }
    if prune {
        let pages: Vec<String> = all.iter().map(|(p, _)| page_name(p)).collect();
        for entry in std::fs::read_dir(&out)? {
            let file = entry?.path();
            let name = file
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or_default();
            if !name.ends_with(".md") || pages.iter().any(|p| p == name) {
                continue;
            }
            // only what docs-gen wrote: an index or a guide stays
            if std::fs::read_to_string(&file).is_ok_and(|t| t.contains(START)) {
                std::fs::remove_file(&file)?;
                eprintln!("removed {}", file.display());
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nested_commands_get_their_own_pages() {
        let cmd = clap::Command::new("t").subcommand(
            clap::Command::new("snapshot")
                .subcommand(clap::Command::new("save"))
                .subcommand(clap::Command::new("ls").hide(true)),
        );
        let mut all = Vec::new();
        commands(&cmd, &[], &mut all);
        let names: Vec<String> = all.iter().map(|(p, _)| page_name(p)).collect();
        assert_eq!(names, ["snapshot.md", "snapshot-save.md"]);
    }

    #[test]
    fn counts_fill_their_markers_and_refuse_unknown_names() {
        let counts: std::collections::BTreeMap<&'static str, String> =
            [("cli-commands", "40".to_string())].into_iter().collect();
        assert_eq!(
            fill_counts(
                "has <!-- count:cli-commands -->28<!-- /count --> commands, \
                 <!-- count: cli-commands -->x<!-- /count -->.",
                &counts
            )
            .unwrap(),
            "has <!-- count:cli-commands -->40<!-- /count --> commands, \
             <!-- count:cli-commands -->40<!-- /count -->."
        );
        assert!(fill_counts("<!-- count:nope -->1<!-- /count -->", &counts).is_err());
        assert!(fill_counts("<!-- count:cli-commands -->1", &counts).is_err());
    }

    #[test]
    fn every_count_has_a_value() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let counts = counts(&root);
        assert_eq!(
            counts["cli-commands"],
            crate::cli::GROUPS
                .iter()
                .map(|(_, c)| c.len())
                .sum::<usize>()
                .to_string()
        );
        for (name, value) in &counts {
            assert!(!value.is_empty() && value != "0", "{name} = {value:?}");
        }
    }

    #[test]
    fn the_index_lists_every_command_under_its_group() {
        let cmd = crate::command();
        let text = index(&cmd);
        for (group, names) in crate::cli::GROUPS {
            assert!(text.contains(&format!("## {group}\n")), "{group}");
            for name in *names {
                assert_eq!(
                    text.matches(&format!("[`{name}`]({name}.md)")).count(),
                    1,
                    "{name}"
                );
            }
        }
    }

    #[test]
    fn prune_keeps_pages_it_did_not_write() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("README.md"), "# index\n").unwrap();
        std::fs::write(
            dir.path().join("gone.md"),
            format!("# gone\n\n{START}\n\n{END}\n"),
        )
        .unwrap();
        run(
            &Ctx {
                format: crate::output::Format::Text,
                json: false,
                quiet: true,
                verbose: false,
            },
            Args {
                out: dir.path().to_path_buf(),
                schemas: None,
                prune: true,
                list_commands: false,
                root: dir.path().to_path_buf(),
            },
        )
        .unwrap();
        assert!(dir.path().join("README.md").exists());
        assert!(!dir.path().join("gone.md").exists());
        assert!(dir.path().join("deploy.md").exists());
    }
}
